export function respondLocalized(ctx: EngineContext, lang: Lang): AIResponse {
  const copy = REPLIES[lang];
  if (!copy) {
    throw new Error(`No localized AI responses are configured for ${lang}.`);
  }

  const message = ctx.message.trim();
  const pii = detectPII(message);
  const warning = pii.found ? copy.pii : undefined;
  const unsafe = detectUnsafe(message);
  const classified = classifyProblem(message).category;
  const localizedMatch = Object.entries(CATEGORY_PATTERNS)
    .find(([, pattern]) => pattern.test(message))?.[0] as CategoryKey | undefined;
  const localizedCategory = localizedMatch?.startsWith("WATER")
    ? "WATER"
    : localizedMatch?.startsWith("ROADS")
    ? "ROADS"
    : localizedMatch?.startsWith("ELECTRICITY")
    ? "ELECTRICITY"
    : localizedMatch;
  const category: CategoryKey = classified !== "OTHER"
    ? classified
    : /पाणी/.test(message) ? "WATER" : localizedCategory ?? "OTHER";

  let text: string;
  if (unsafe) {
    text = copy.safety;
  } else if (/^(hi|hello|hey|namaste|ନମସ୍କାର|নমস্কার|నమస్కారం|வணக்கம்|નમસ્તે|ನಮಸ್ಕಾರ|നമസ്കാരം|ਸਤਿ ਸ੍ਰੀ ਅਕਾਲ|السلام علیکم)/i.test(message)) {
    text = copy.greeting;
  } else if (category !== "OTHER" || copy.detect.test(message)) {
    text = category === "WATER" ? copy.water
      : category === "ROADS" ? copy.roads
      : category === "ELECTRICITY" ? copy.electricity
      : category === "GARBAGE" || category === "DRAINAGE" ? copy.sanitation
      : copy.general;
  } else {
    text = copy.general;
  }

  const needsMoreLocation = Boolean(ctx.locationLookupComplete && ctx.verifiedLocation && ctx.verifiedLocation.type !== "VILLAGE");
  const needsLocation = Boolean(ctx.locationLookupComplete && !ctx.verifiedLocation && category !== "OTHER");
  const verifiedPath = ctx.verifiedLocation?.path.filter((part) => part !== "India").join(", ");
  if (needsMoreLocation && verifiedPath) {
    text = `${text}\n\n${locationFollowUp(lang)}\n📍 ${verifiedPath}`;
  }

  return {
    text,
    infoType: "ai",
    language: lang,
    detectedCategory: category === "OTHER" ? undefined : category,
    suggestedActions: category === "OTHER" || needsMoreLocation || needsLocation ? undefined : [{
      label: copy.reportAction,
      action: "create_report",
      payload: { category, description: message, location: "" },
    }],
    warning,
    needsInfo: category === "OTHER" ? undefined : [needsMoreLocation ? "wardOrLocality" : "location"],
  };
}
